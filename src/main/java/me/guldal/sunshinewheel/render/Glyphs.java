    /** Türkçe harfleri ve küçük harfleri fontun desteklediği karakterlere çevirir. */
    public static String ascii(String text) {
        StringBuilder out = new StringBuilder(text.length());
        for (char c : text.toCharArray()) {
            char m = switch (c) {
                case 'ı', 'İ', 'i' -> 'I';
                case 'ğ', 'Ğ' -> 'G';
                case 'ü', 'Ü' -> 'U';
                case 'ş', 'Ş' -> 'S';
                case 'ö', 'Ö' -> 'O';
                case 'ç', 'Ç' -> 'C';
                case 'â' -> 'A';
                default -> Character.toUpperCase(c);
            };
            out.append(FONT.containsKey(m) ? m : ' ');
        }
        return out.toString();
    }

    public static int textWidth(String text, int scale) {
        int chars = ascii(text).length();
        return chars == 0 ? 0 : (chars * (WIDTH + SPACING) - SPACING) * scale;
    }

    /** Metni sol üst köşesi (x, y) olacak şekilde çizer. */
    public static void draw(PixelImage image, int x, int y, String text, int rgb, int scale) {
        int cursor = x;
        for (char c : ascii(text).toCharArray()) {
            String[] glyph = FONT.get(c);
            if (glyph != null) {
                for (int row = 0; row < HEIGHT; row++) {
                    for (int col = 0; col < WIDTH; col++) {
                        if (glyph[row].charAt(col) == '#') {
                            image.fillRect(cursor + col * scale, y + row * scale, scale, scale, 0xFF000000 | rgb);
                        }
                    }
                }
            }
            cursor += (WIDTH + SPACING) * scale;
        }
    }

    public static void drawCentered(PixelImage image, int centerX, int y, String text, int rgb, int scale) {
        draw(image, centerX - textWidth(text, scale) / 2, y, text, rgb, scale);
    }
